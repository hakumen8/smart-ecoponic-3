export function t(lang, key) {
  return DICT[lang]?.[key] ?? DICT.en[key] ?? key;
}

export function objectName(lang, type) {
  const pair = NAMES[type];
  if (!pair) return type;
  return lang === "ar" ? pair[0] : pair[1];
}

export function layerName(lang, id) {
  const pair = LAYERS[id];
  if (!pair) return id;
  return lang === "ar" ? pair[0] : pair[1];
}

export function materialName(lang, id) {
  const pair = MATERIALS[id];
  if (!pair) return id;
  return lang === "ar" ? pair[0] : pair[1];
}
